"""Create evidence/AI_A2_2527889_TEST_LOG.pdf and the declaration PDF.

Usage:  python tools/make_evidence.py
Runs ``pytest -q``, stores the output, and writes the PDFs. The declaration is a
text you must READ, edit if any sentence is untrue for you, print and sign.
"""
from __future__ import annotations

import datetime as dt
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from reportlab.lib.pagesizes import A4  # noqa: E402
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet  # noqa: E402
from reportlab.lib.units import cm  # noqa: E402
from reportlab.platypus import Paragraph, Preformatted, SimpleDocTemplate, Spacer  # noqa: E402

from src.config import FULL_NAME, PROJECT_NAME, REG_NUMBER, STUDENT_ID, VERIFICATION_CODE, Paths  # noqa: E402

ss = getSampleStyleSheet()
BODY = ParagraphStyle("b", parent=ss["BodyText"], fontSize=10.5, leading=15, spaceAfter=8)
MONO = ParagraphStyle("m", parent=ss["Code"], fontName="Courier", fontSize=8, leading=10)


def make_test_log(paths: Paths) -> None:
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q"], cwd=ROOT,
                          capture_output=True, text=True)
    output = proc.stdout + proc.stderr
    (paths.artifacts / "pytest_output.txt").write_text(output, encoding="utf-8")
    now = dt.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S %Z")
    header = (f"{FULL_NAME} | {REG_NUMBER} | {VERIFICATION_CODE}\n"
              f"Date/time: {now}\nOS: {platform.platform()}\nPython: {platform.python_version()}\n"
              f"Command: pytest -q   (exit code {proc.returncode})\n" + "-" * 90 + "\n")
    paths.evidence.mkdir(exist_ok=True)
    doc = SimpleDocTemplate(str(paths.evidence / f"{PROJECT_NAME}_TEST_LOG.pdf"), pagesize=A4,
                            leftMargin=1.5 * cm, rightMargin=1.5 * cm, title="pytest log")
    doc.build([Paragraph("Automated test log", ss["Heading1"]), Preformatted(header + output, MONO)])
    print("test log written; pytest exit code", proc.returncode)


def make_declaration(paths: Paths) -> None:
    items = [
        f"I, {FULL_NAME}, registration number {REG_NUMBER} (institutional username {STUDENT_ID}), "
        f"declare that this submission ({PROJECT_NAME}, verification code {VERIFICATION_CODE}) is "
        "my own individual work for the Artificial Intelligence project.",
        "The dataset is synthetic and was generated by my own script from the seed 7889; I did not "
        "edit the CSV by hand.",
        "I used Claude (Anthropic) to help debug the project and organize and improve its PDFs; it "
        "did not generate the project code. GitHub Copilot (Copilot SDK in VS Code) helped check "
        "assignment requirements, update README and cache exclusions, run the pipeline, prediction "
        "examples and tests, regenerate pipeline artifacts and PDFs, and publish the project snapshot. "
        "It also updated the existing evidence-PDF script to correct this AI attribution. How AI "
        "tools were used is recorded in evidence/AI_USE.md.",
        "I have run the system, reviewed the code and the outputs, and I can explain my model "
        "choices and interpretations and make a small change to my own code.",
        "I wrote or rewrote the interpretation of one regression error, one classification error and "
        "one cluster in my own words.",
        "The project contains no passwords, tokens, private keys, virtual environments or unrelated datasets.",
    ]
    story = [Paragraph("Declaration of originality and responsible use", ss["Heading1"]), Spacer(1, 8)]
    story += [Paragraph(f"{i}. {t}", BODY) for i, t in enumerate(items, 1)]
    story += [Spacer(1, 30), Paragraph("Signature: ______________________________", BODY),
              Paragraph("Date: ______________________________", BODY)]
    paths.evidence.mkdir(exist_ok=True)
    SimpleDocTemplate(str(paths.evidence / f"{PROJECT_NAME}_DECLARATION.pdf"), pagesize=A4,
                      leftMargin=2.2 * cm, rightMargin=2.2 * cm, title="Declaration").build(story)
    print("declaration written")


if __name__ == "__main__":
    p = Paths()
    make_test_log(p)
    make_declaration(p)
    from src.report import build_report
    build_report(p)  # refresh report so it quotes the latest test result
